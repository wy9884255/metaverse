def mp3_bytes_to_trimmed_pcm(mp3_bytes: bytes) -> np.ndarray:
    proc = subprocess.run(
        [FFMPEG, "-y", "-i", "pipe:0", "-f", "f32le", "-acodec", "pcm_f32le", "-ar", str(SR), "-ac", "1", "-"],
        input=mp3_bytes,
        capture_output=True,
        check=True,
    )
    pcm = np.frombuffer(proc.stdout, dtype=np.float32).copy()
    ab = np.abs(pcm)
    idx_head = np.where(ab > 0.0022)[0]
    idx_tail = np.where(ab > 0.00012)[0]
    if len(idx_head) > 0 and len(idx_tail) > 0:
        i0 = max(0, int(idx_head[0]) - int(0.025 * SR))
        i1 = min(len(pcm), int(idx_tail[-1]) + int(0.220 * SR))
        pcm = pcm[i0:i1]
    fi = min(len(pcm), int(0.014 * SR))
    fo = min(len(pcm), int(0.045 * SR))
    if fi > 0:
        pcm[:fi] *= np.linspace(0.0, 1.0, fi, dtype=np.float32)
    if fo > 0:
        pcm[-fo:] *= np.linspace(1.0, 0.0, fo, dtype=np.float32)
    return pcm


def warm_studio_mastering(pcm: np.ndarray) -> np.ndarray:
    if len(pcm) < 64:
        return pcm
    fft = np.fft.rfft(pcm)
    freqs = np.fft.rfftfreq(len(pcm), d=1.0 / SR)
    warm = 1.0 + 0.16 * np.exp(-((freqs - 185.0) / 110.0) ** 2)
    de_harsh = 1.0 - 0.16 * np.exp(-((freqs - 5600.0) / 2100.0) ** 2)
    air = 1.0 + 0.06 * np.exp(-((freqs - 11200.0) / 3000.0) ** 2)
    shaped = np.fft.irfft(fft * warm * de_harsh * air, n=len(pcm)).astype(np.float32)
    shaped = np.tanh(shaped * 1.10) / np.tanh(1.10)
    peak = float(np.max(np.abs(shaped)))
    if peak > 0.92:
        shaped *= 0.92 / peak
    return shaped


def split_beat_into_subcues(text: str, start_s: float, dur_s: float) -> list[dict]:
    # Split long beat sentences (> 26 chars) across major clauses so each screen subtitle stays 1-2 clean lines!
    clean = text.replace("……", "，").replace("——", "，")
    raw_parts = [p.strip() for p in re.split(r"(?<=[，；：。！？])", text) if p.strip()]
    merged = []
    acc = ""
    for p in raw_parts:
        if len(acc) + len(p) <= 26 or len(acc) < 8:
            acc += p
        else:
            merged.append(acc)
            acc = p
    if acc:
        merged.append(acc)
    if not merged:
        merged = [text]

    weights = []
    for m in merged:
        n_chars = len(re.sub(r"[，。！？；：、…—\s]", "", m))
        pause_w = 2.6 if re.search(r"(……|——|[。！？；：])$", m) else (1.1 if m.endswith("，") else 0.3)
        weights.append(max(1.0, n_chars + pause_w))
    tot_w = sum(weights) or 1.0
    out = []
    cur = start_s
    for m, w in zip(merged, weights):
        d = dur_s * (w / tot_w)
        disp = re.sub(r"[，。；：]+$", "", m.replace("……", " ").strip())
        out.append({"text": disp, "t0": round(cur, 3), "t1": round(cur + d, 3)})
        cur += d
    return out


async def synth_beat_pcm(text: str, rate: str, pitch: str) -> np.ndarray:
    for attempt in range(4):
        try:
            buf = io.BytesIO()
            comm = edge_tts.Communicate(text=text, voice=VOICE, rate=rate, pitch=pitch)
            async for chunk in comm.stream():
                if chunk["type"] == "audio":
                    buf.write(chunk["data"])
            return mp3_bytes_to_trimmed_pcm(buf.getvalue())
        except Exception as exc:
            if attempt == 3:
                raise
            await asyncio.sleep(1.2 * (attempt + 1))
    raise RuntimeError("Unreachable")


async def build_all():
    import sys
    only_ids = None
    if "--only" in sys.argv:
        idx = sys.argv.index("--only")
        if idx + 1 < len(sys.argv):
            only_ids = set(x.strip() for x in sys.argv[idx + 1].split(",") if x.strip())

    os.makedirs(OUT_DIR, exist_ok=True)
    exported_episodes = []

    for ep in EPISODES:
        ep_dir = os.path.join(OUT_DIR, ep["id"])
        os.makedirs(ep_dir, exist_ok=True)
        cached_manifest = os.path.join(ep_dir, "manifest.json")
        if only_ids and ep["id"] not in only_ids and os.path.exists(cached_manifest):
            with open(cached_manifest, "r", encoding="utf-8") as cmf:
                cm = json.load(cmf)
            all_mp3_ok = True
            for s in cm["segments"]:
                mp3_p = os.path.join(ep_dir, f"seg_{s['index']+1:02d}.mp3")
                if not os.path.exists(mp3_p):
                    all_mp3_ok = False
                    break
                with open(mp3_p, "rb") as f:
                    s["audioDataUri"] = "data:audio/mpeg;base64," + base64.b64encode(f.read()).decode("ascii")
            if all_mp3_ok:
                print(f"[{ep['id']}] Reused cached manifest + {len(cm['segments'])} MP3 segments ({cm['totalDuration']}s)")
                exported_episodes.append(cm)
                continue

        t_cursor = 0.50  # Gentle opening breath before narration starts
        seg_out = []

        for i, seg in enumerate(ep["segments"]):
            mp3_path = os.path.join(ep_dir, f"seg_{i+1:02d}.mp3")
            pieces = []
            cues = []
            local_t = 0.0
            full_text_parts = []

            for b_idx, (b_text, b_rate, b_pitch, b_pause) in enumerate(seg["beats"]):
                pcm = await synth_beat_pcm(b_text, b_rate, b_pitch)
                b_dur = len(pcm) / float(SR)
                # Extend last subcue across the dramatic pause so subtitle stays calmly readable until next thought begins
                sub_cues = split_beat_into_subcues(b_text, t_cursor + local_t, b_dur)
                if sub_cues:
                    sub_cues[-1]["t1"] = round(t_cursor + local_t + b_dur + min(b_pause * 0.85, 0.65), 3)
                cues.extend(sub_cues)
                full_text_parts.append(b_text)
                pieces.append(pcm)

                # Keep inter-beat pauses inside the segment MP3 except the final trailing scene gap
                if b_idx < len(seg["beats"]) - 1:
                    pieces.append(np.zeros(int(round(b_pause * SR)), dtype=np.float32))
                    local_t += b_dur + b_pause
                else:
                    local_t += b_dur
                    tail_pause = b_pause

            seg_pcm = warm_studio_mastering(np.concatenate(pieces))
            voice_dur = round(len(seg_pcm) / float(SR), 3)
            pcm16 = np.clip(seg_pcm * 32767.0, -32768, 32767).astype(np.int16)
            subprocess.run(
                [FFMPEG, "-y", "-f", "s16le", "-ar", str(SR), "-ac", "1", "-i", "pipe:0", "-b:a", "160k", mp3_path],
                input=pcm16.tobytes(),
                capture_output=True,
                check=True,
            )
            with open(mp3_path, "rb") as f:
                raw_mp3 = f.read()
            b64 = "data:audio/mpeg;base64," + base64.b64encode(raw_mp3).decode("ascii")

            t0 = round(t_cursor, 3)
            t1 = round(t0 + voice_dur + tail_pause, 3)
            seg_out.append({
                "index": i,
                "scene": seg["scene"],
                "tag": seg["tag"],
                "text": "".join(full_text_parts),
                "t0": t0,
                "voiceEnd": round(t0 + voice_dur, 3),
                "t1": t1,
                "duration": voice_dur,
                "cues": cues,
                "audioDataUri": b64,
            })
            print(f"[{ep['id']}] seg_{i+1:02d} ({seg['scene']}): {t0:.2f}s -> {t1:.2f}s (voice={voice_dur:.2f}s, {len(cues)} cues)")
            t_cursor = t1

        ep_manifest = {
            "id": ep["id"],
            "title": ep["title"],
            "bgmPreset": ep["bgmPreset"],
            "totalDuration": round(t_cursor, 3),
            "voice": VOICE,
            "segments": seg_out,
        }
        with open(os.path.join(ep_dir, "manifest.json"), "w", encoding="utf-8") as mf:
            json.dump(
                {k: v for k, v in ep_manifest.items() if k != "segments"}
                | {"segments": [{kk: vv for kk, vv in s.items() if kk != "audioDataUri"} for s in seg_out]},
                mf,
                ensure_ascii=False,
                indent=2,
            )
        exported_episodes.append(ep_manifest)

    logo_path = os.path.join(WORKSPACE, "pov_space_logo_transparent.png")
    wordmark_path = os.path.join(WORKSPACE, "logo_universe_pov_wordmark_transparent.png")
    bgm_piano = os.path.join(WORKSPACE, "bgm_interstellar_piano.mp3")
    bgm_path = bgm_piano if os.path.exists(bgm_piano) else os.path.join(WORKSPACE, "bgm_interstellar_cornfield.mp3")
    logo_b64 = ""
    wordmark_b64 = ""
    bgm_b64 = ""
    if os.path.exists(logo_path):
        with open(logo_path, "rb") as lf:
            logo_b64 = "data:image/png;base64," + base64.b64encode(lf.read()).decode("ascii")
    if os.path.exists(wordmark_path):
        with open(wordmark_path, "rb") as wf:
            wordmark_b64 = "data:image/png;base64," + base64.b64encode(wf.read()).decode("ascii")
    if os.path.exists(bgm_path):
        with open(bgm_path, "rb") as bf:
            bgm_b64 = "data:audio/mpeg;base64," + base64.b64encode(bf.read()).decode("ascii")

    js_payload = (
        "// Auto-generated by generate_voiceover.py (VivienneMultilingual anthropomorphic documentary female narration)\n"
        "window.UNIVERSE_STUDIO_PACK = "
        + json.dumps(
            {
                "logoDataUri": logo_b64,
                "wordmarkDataUri": wordmark_b64,
                "interstellarBgmDataUri": bgm_b64,
                "episodes": exported_episodes,
            },
            ensure_ascii=False,
        )
        + ";\n"
    )
    js_path = os.path.join(WORKSPACE, "episodes_audio.js")
    with open(js_path, "w", encoding="utf-8") as jf:
        jf.write(js_payload)
    print(f"Saved {js_path} ({len(js_payload) / 1024:.1f} KB)")


